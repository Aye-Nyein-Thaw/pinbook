<?php

use App\Models\User;

test('login screen can be rendered', function () {
    $response = $this->get('/login');

    $response->assertStatus(200);
});

test('users can authenticate using the login screen', function () {
    $user = User::factory()->create();

    $response = $this->post('/login', [
        'email' => $user->email,
        'password' => 'password',
    ]);

    $this->assertAuthenticated();
    $response->assertRedirect(route('dashboard', absolute: false));
});

test('users are sent back to the page they came from after logging in', function () {
    $user = User::factory()->create();

    $this->get('/login?'.http_build_query(['redirect' => '/trips/1#comments']));

    $response = $this->post('/login', [
        'email' => $user->email,
        'password' => 'password',
    ]);

    $this->assertAuthenticated();
    $response->assertRedirect('/trips/1#comments');
});

test('a redirect to another site is ignored after logging in', function (string $redirect) {
    $user = User::factory()->create();

    $this->get('/login?'.http_build_query(['redirect' => $redirect]));

    $response = $this->post('/login', [
        'email' => $user->email,
        'password' => 'password',
    ]);

    $this->assertAuthenticated();
    $response->assertRedirect(route('dashboard', absolute: false));
})->with([
    'a full url' => 'https://evil.example/steal',
    'a protocol-relative url' => '//evil.example/steal',
    'a backslash trick' => '/\\evil.example/steal',
]);

test('users can not authenticate with invalid password', function () {
    $user = User::factory()->create();

    $this->post('/login', [
        'email' => $user->email,
        'password' => 'wrong-password',
    ]);

    $this->assertGuest();
});

test('users can logout', function () {
    $user = User::factory()->create();

    $response = $this->actingAs($user)->post('/logout');

    $this->assertGuest();
    $response->assertRedirect('/');
});
